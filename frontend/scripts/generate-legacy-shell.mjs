#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sourcePath = path.join(packageRoot, 'legacy-shell', 'index.html');
const outputPath = path.join(packageRoot, 'generated', 'legacy-shell.ts');
const includePattern = /^[ \t]*<!--\s*@include\s+([^\s]+?)\s*-->[ \t]*\r?\n?/gm;

function expandFile(filePath, stack = new Set()) {
  const resolved = path.resolve(filePath);
  if (stack.has(resolved)) {
    throw new Error(`Circular shell include: ${resolved}`);
  }
  const nextStack = new Set(stack).add(resolved);
  const source = fs.readFileSync(resolved, 'utf8');
  return source.replace(includePattern, (_match, includePath) =>
    expandFile(path.resolve(path.dirname(resolved), includePath), nextStack),
  );
}

function innerHtml(documentHtml, tag) {
  const match = documentHtml.match(
    new RegExp(`<${tag}[^>]*>([\\s\\S]*?)<\\/${tag}>`, 'i'),
  );
  if (!match) {
    throw new Error(`Legacy shell is missing <${tag}>.`);
  }
  return match[1].trim();
}

const expanded = expandFile(sourcePath);
const head = innerHtml(expanded, 'head')
  .replace(
    /\s*<link\s+rel=["']stylesheet["']\s+href=["']\/src\/styles\.css["']\s*\/?>/i,
    '',
  )
  .trim();
const body = innerHtml(expanded, 'body')
  .replace(
    /\s*<script\s+type=["']module["']\s+src=["']\/src\/[^"']+\.ts["']><\/script>/gi,
    '',
  )
  .trim();
const generated =
  '// Generated by scripts/generate-legacy-shell.mjs. Do not edit.\n' +
  `export const legacyHeadHtml = ${JSON.stringify(head)};\n\n` +
  `export const legacyShellHtml = ${JSON.stringify(body)};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) {
  fs.writeFileSync(outputPath, generated);
}
